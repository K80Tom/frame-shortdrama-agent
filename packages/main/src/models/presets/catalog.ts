function definePreset(input: Omit<ModelPresetEntry, 'defaultBaseUrl'> & { defaultBaseUrl?: string }): ModelPresetEntry {
  const provider = PROVIDER_CATALOG.find(item => item.id === input.providerId);
  if (!provider) throw new Error(`模型预设 ${input.code} 引用了不存在的服务商 ${input.providerId}`);
  return { ...input, defaultBaseUrl: input.defaultBaseUrl ?? provider.defaultBaseUrl };
}

